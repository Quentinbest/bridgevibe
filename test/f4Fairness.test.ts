import { writeFileSync } from 'node:fs';
import { expect, test } from 'vitest';
import { bridgeDdsAdapter } from '../src/analysis/bridgeDdsAdapter';
import { sampledEstimate } from '../src/analysis/sampledEstimate';
import { teacherLabels } from '../src/coach/teacherLabels';
import { REVIEW_SAMPLE_COUNT, REVIEW_TOLERANCE } from '../src/information/parameters';
import { cardName } from '../src/explanation';
import { SEATS, sameCard, seatViewSeed, type Card } from '../src/table';
import { f4Position, points } from './f4/records';

// US-48.1, T6, VAL-12: how often double-dummy alone would blame a play the F4 labels accept.
// The sampled cost uses the review's own derivation (#27): the learner's historical Seat View,
// seatViewSeed, REVIEW_SAMPLE_COUNT samples. Regenerate with `npm run f4:fairness`.
type Row = { ref: string; cards: readonly Card[]; ddCost: number; sampledCost: number; acceptable: boolean | null; source: string | null };
test('T6: fair-feedback study over the F4 decisions', async () => {
  const started = performance.now();
  const decisions: { index: number; dealId: string; trick: number; rows: Row[] }[] = [];
  for (const [index, point] of points.entries()) {
    const labels = teacherLabels[index];
    expect(labels.dealId).toBe(point.dealId);
    const table = f4Position(point);
    const declarer = table.record().contract.declarer;
    const seat = table.seatView('south').turn!;
    const view = table.seatView(seat === SEATS[(SEATS.indexOf(declarer) + 2) % 4] ? declarer : seat);
    const legal = table.legalActions(seat).map(action => action.card);
    const estimate = await sampledEstimate(bridgeDdsAdapter, view, legal, REVIEW_SAMPLE_COUNT, seatViewSeed(view), Infinity);
    if ('abstention' in estimate) throw new Error(`Sampling abstained at ${point.dealId}`);
    const layout = { north: table.seatView('north').hand, east: table.seatView('east').hand,
      south: table.seatView('south').hand, west: table.seatView('west').hand };
    const actual = await bridgeDdsAdapter.solvePosition(layout, { strain: view.contract.strain,
      leader: view.currentTrick[0]?.seat ?? seat, currentTrick: view.currentTrick });
    const tricks = (classes: readonly { cards: readonly Card[]; tricks: number }[], card: Card) =>
      classes.find(c => c.cards.some(k => sameCard(k, card)))!.tricks;
    const values = labels.candidates.map(c => ({ c, dd: tricks(actual.classes, c.cards[0]), sampled: tricks(estimate.classes, c.cards[0]) }));
    const bestDd = Math.max(...values.map(v => v.dd)), bestSampled = Math.max(...values.map(v => v.sampled));
    decisions.push({ index: index + 1, dealId: point.dealId, trick: view.tricks.length + 1, rows: values.map(({ c, dd, sampled }) => ({
      ref: c.ref, cards: c.cards, ddCost: bestDd - dd, sampledCost: bestSampled - sampled, acceptable: c.acceptable, source: c.source })) });
  }
  const rows = decisions.flatMap(d => d.rows);
  const acceptable = rows.filter(r => r.acceptable === true);
  const ddBlames = acceptable.filter(r => r.ddCost > 0);
  const sampledBlames = acceptable.filter(r => r.sampledCost > REVIEW_TOLERANCE);
  const decisionsBlamed = decisions.filter(d => d.rows.some(r => r.acceptable === true && r.ddCost > 0));
  expect(rows).toHaveLength(teacherLabels.reduce((n, l) => n + l.candidates.length, 0));
  expect(rows.every(r => r.acceptable !== null)).toBe(true);
  expect(acceptable.length).toBeGreaterThan(0);
  const pct = (n: number, d: number) => `${(100 * n / d).toFixed(1)}%`;
  const sources = [...new Set(rows.map(r => r.source))].sort().join(', ');
  const name = (cards: readonly Card[]) => cards.map(cardName).join(' / ');
  const report = `# Fair-feedback study (T6, VAL-12)

Generated by \`npm run f4:fairness\` from \`docs/domain/f4-draft/\` and \`src/coach/f4-labels.json\`. Real Table replay of each F4 position; bridge-dds ${bridgeDdsAdapter.version} on the actual layout; ${REVIEW_SAMPLE_COUNT} samples per point on the learner's historical Seat View, seeded with \`seatViewSeed\` (the review's derivation, #27).

**Label source: ${sources}.** Under PRD D10 these are AI annotators' labels, with AI adjudication of their 23 disagreements; the teachers' review is pending (#100). Rates below measure double-dummy against those labels, not against teachers.

## Result

- Acceptable plays (by the F4 labels): **${acceptable.length}** of ${rows.length} candidate classes, over ${decisions.length} decisions.
- **Double-dummy alone would blame ${ddBlames.length} of them (${pct(ddBlames.length, acceptable.length)})**: a positive trick cost on the actual layout. These are on ${decisionsBlamed.length} of ${decisions.length} decisions.
- For comparison, the sampled estimate (#27, tolerance ${REVIEW_TOLERANCE} tricks) would call ${sampledBlames.length} of them (${pct(sampledBlames.length, acceptable.length)}) not acceptable.

Costs are tricks for the side to act: double-dummy cost is the best class's tricks on the actual layout minus this class's; sampled cost is the same over the samples (expected tricks).

## Per decision

| Decision | Deal | Trick | Candidate | Double-dummy cost | Sampled cost | Label | Source |
| --- | --- | --- | --- | --- | --- | --- | --- |
${decisions.flatMap(d => d.rows.map((r, i) => `| ${i === 0 ? `D${String(d.index).padStart(2, '0')}` : ''} | ${i === 0 ? d.dealId : ''} | ${i === 0 ? d.trick : ''} | ${name(r.cards)} | ${r.ddCost} | ${r.sampledCost.toFixed(2)} | ${r.acceptable ? 'acceptable' : 'not acceptable'} | ${r.source} |`)).join('\n')}
`;
  console.log(`T6: ${ddBlames.length}/${acceptable.length} acceptable plays blamed by double-dummy; ${(performance.now() - started).toFixed(0)} ms`);
  if (process.env.F4_FAIRNESS_REPORT === '1') writeFileSync(new URL('../docs/reports/fair-feedback.md', import.meta.url), report);
}, 180_000);
